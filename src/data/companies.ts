// 時価総額（億円単位）を読みやすい日本語表記（兆円 / 億円）にフォーマット
export function formatMarketCapOku(oku: number, digits: number = 2): string {
  const abs = Math.abs(oku);
  const sign = oku < 0 ? "-" : "";
  if (abs >= 10000) {
    return `${sign}${(abs / 10000).toFixed(digits)}兆円`;
  }
  return `${sign}${Math.round(abs).toLocaleString()}億円`;
}

// 時価総額の増減額（億円単位）を符号付きでフォーマット
export function formatSignedMarketCapOku(oku: number, digits: number = 2): string {
  const prefix = oku > 0 ? "+" : "";
  return `${prefix}${formatMarketCapOku(oku, digits)}`;
}

