export interface ManufacturingCompany {
  code: string;                 // 証券コード (例: '7203')
  ticker: string;               // Yahoo Finance ティッカー (例: '7203.T')
  nameJa: string;               // 企業名（日本語）
  nameKana: string;             // ふりがな（検索用）
  nameEn: string;               // 英語表記
  sector: ManufacturingSector;  // 東証33業種（製造業16業種）
  subCategory: string;          // 細分類（例: '完成車・モビリティ'）
  description: string;          // 企業の特徴・強み解説
  tags: string[];               // 主力製品・テーマタグ
  marketCapOku: number;         // 時価総額（億円単位：478000 = 47.8兆円）
  per: number;                  // 予想PER (倍)
  pbr: number;                  // 実績PBR (倍)
  dividendYield: number;        // 配当利回り (%)
  roe: number;                  // ROE (%)
  operatingMargin: number;      // 営業利益率 (%)
  basePrice: number;            // 初期表示・フォールバック基準株価 (円)
  baseChangePercent: number;    // 初期表示前日比 (%)
  peers: string[];              // 同業比較おすすめ銘柄コード
}

